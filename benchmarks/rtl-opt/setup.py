PROGRAM_MD = """You are optimizing a small Verilog module (Sky130).
The harness evaluates your changes — do NOT run make, lint, test, or synth yourself.

Make ONE focused RTL change to reduce gate count while keeping tests passing.
Your change is kept if it reduces cell count without breaking functional equivalence.
Only edit .v files in rtl/. Do NOT touch tb/, synth/, golden/, or Makefile.

After your edit, write a one-line summary of what you changed and why to the file rtl/.change_summary (overwrite it each time).

Do NOT change the module port interface (signal names, widths, directions).
"""


def gen_cosim_testbench(design_name: str, verilog_path: Path) -> str:
    """Generate a co-simulation testbench that compares original vs modified."""
    # Parse module ports from the Verilog file
    with open(verilog_path) as f:
        content = f.read()

    # Simple port extraction: find module declaration
    import re
    # Match module ports
    mod_match = re.search(
        rf'module\s+{re.escape(design_name)}\s*\((.*?)\)\s*;',
        content, re.DOTALL
    )
    if not mod_match:
        # Fallback: just compile and run, no comparison
        return _fallback_tb(design_name)

    # Extract only the top module body (from its declaration to the next
    # 'endmodule'), so we don't pick up ports from helper modules.
    top_start = mod_match.start()
    endmod = re.search(r'\bendmodule\b', content[top_start:])
    top_body = content[top_start:top_start + endmod.end()] if endmod else content[top_start:]

    # Find input/output declarations in the top module body only
    inputs = []
    outputs = []
    for line in top_body.split('\n'):
        line = line.strip().rstrip(',').rstrip(';')
        # Match: input/output [wire/reg] [signed] [width] name
        m = re.match(
            r'(input|output)\s+(?:wire\s+|reg\s+)?(?:signed\s+)?(\[.*?\])?\s*(\w+)',
            line
        )
        if m:
            direction, width, name = m.groups()
            width = width or ""
            # Skip if we captured a Verilog keyword as the name
            if name in ('wire', 'reg', 'signed', 'input', 'output'):
                continue
            if direction == 'input':
                inputs.append((name, width))
            else:
                outputs.append((name, width))

    if not inputs or not outputs:
        return _fallback_tb(design_name)

    # Generate testbench
    tb = [f"`timescale 1 ns / 1 ps\n"]
    tb.append(f"module cosim_tb;\n")

    # Declare signals
    has_clk = any(n == 'clk' for n, _ in inputs)
    has_rst = any(n in ('rst', 'reset', 'rst_n', 'resetn') for n, _ in inputs)

    for name, width in inputs:
        tb.append(f"  reg {width} {name};")
    tb.append("")
    for name, width in outputs:
        tb.append(f"  wire {width} dut_{name};")
        tb.append(f"  wire {width} ref_{name};")
    tb.append("")

    # Instantiate DUT (modified design)
    ports_dut = ", ".join(f".{n}({n})" if (n, w) in inputs
                          else f".{n}(dut_{n})" for n, w in inputs + outputs)
    tb.append(f"  {design_name} dut ({ports_dut});\n")

    # Instantiate reference (original, renamed module)
    ports_ref = ", ".join(f".{n}({n})" if (n, w) in inputs
                          else f".{n}(ref_{n})" for n, w in inputs + outputs)
    tb.append(f"  {design_name}_original ref_inst ({ports_ref});\n")

    # Clock generation if needed
    if has_clk:
        tb.append("  always #5 clk = ~clk;\n")

    # Test stimulus
    tb.append("  integer i;")
    tb.append("  integer errors = 0;\n")
    tb.append("  initial begin")
    if has_clk:
        tb.append("    clk = 0;")
    # Initialize inputs
    for name, _ in inputs:
        if name not in ('clk', 'rst', 'reset', 'rst_n', 'resetn'):
            tb.append(f"    {name} = 0;")

    if has_rst:
        rst_name = next(n for n, _ in inputs if n in ('rst', 'reset', 'rst_n', 'resetn'))
        active_low = rst_name in ('rst_n', 'resetn')
        tb.append(f"    {rst_name} = {0 if active_low else 1};")
        tb.append(f"    #20;")
        tb.append(f"    {rst_name} = {1 if active_low else 0};")
        tb.append(f"    #10;")

    tb.append("")
    tb.append("    // Random stimulus")
    tb.append("    for (i = 0; i < 1000; i = i + 1) begin")
    for name, _ in inputs:
        if name not in ('clk', 'rst', 'reset', 'rst_n', 'resetn'):
            tb.append(f"      {name} = $random;")
    if has_clk:
        tb.append("      @(posedge clk);")
        tb.append("      @(negedge clk);")
    else:
        tb.append("      #10;")

    # Compare outputs
    for name, _ in outputs:
        tb.append(f"      if (dut_{name} !== ref_{name}) begin")
        tb.append(f'        $display("FAIL: {name} mismatch at i=%0d: dut=%h ref=%h", i, dut_{name}, ref_{name});')
        tb.append(f"        errors = errors + 1;")
        tb.append(f"      end")
    tb.append("    end")
    tb.append("")
    tb.append('    if (errors == 0)')
    tb.append('      $display("PASS: 1000 random vectors, all outputs match");')
    tb.append('    else')
    tb.append('      $display("FAIL: %0d mismatches", errors);')
    tb.append("    $finish;")
    tb.append("  end")
    tb.append("endmodule")

    return "\n".join(tb) + "\n"


def _fallback_tb(design_name: str) -> str:
    """Fallback: just instantiate and check it doesn't crash."""
    return f"""`timescale 1 ns / 1 ps
module cosim_tb;
  initial begin
    #100;
    $display("PASS: basic instantiation check");
    $finish;
  end
endmodule
"""


def create_original_copy(design_name: str, src_path: Path) -> str:
    """Create a renamed copy of the original design for co-simulation.

    Renames ALL modules (not just the top) by appending _original,
    and updates all instantiations to match. This avoids duplicate
    module name collisions when iverilog compiles both files together.
    """
    import re
    with open(src_path) as f:
        content = f.read()

    # Find all module names defined in this file (skip comments)
    # Only match 'module' at the start of a line (possibly with whitespace)
    module_names = re.findall(r'^\s*module\s+(\w+)', content, re.MULTILINE)

    for mod in module_names:
        # Rename module definition
        content = re.sub(
            rf'\bmodule\s+{re.escape(mod)}\b',
            f'module {mod}_original',
            content,
        )
        # Rename instantiations of this module
        content = re.sub(
            rf'\b{re.escape(mod)}\s+(\w+)\s*\(',
            rf'{mod}_original \1(',
            content,
        )

    return content


def setup_design(design_name: str, src_dir: Path, dry_run: bool = False):
    """Create the AutoSilicon design directory for one RTL-OPT design."""
    design_dir = DESIGNS_DIR / f"rtlopt_{design_name}"
    src_file = src_dir / design_name / f"{design_name}.v"

    if not src_file.exists():
        print(f"  SKIP {design_name}: {src_file} not found")
        return False

    if dry_run:
        print(f"  DRY-RUN: would create {design_dir}")
        return True

    # Create directory structure
    (design_dir / "rtl").mkdir(parents=True, exist_ok=True)
    (design_dir / "tb").mkdir(parents=True, exist_ok=True)
    (design_dir / "synth").mkdir(parents=True, exist_ok=True)

    # Copy RTL
    shutil.copy2(src_file, design_dir / "rtl" / f"{design_name}.v")

    # Create original copy for co-simulation
    original_content = create_original_copy(design_name, src_file)
    (design_dir / "tb" / "original.v").write_text(original_content)

    # Generate co-simulation testbench
    tb_content = gen_cosim_testbench(design_name, src_file)
    (design_dir / "tb" / "cosim_tb.v").write_text(tb_content)

    # Write Makefile
    (design_dir / "Makefile").write_text(
        MAKEFILE_TEMPLATE.format(design_name=design_name))

    # Write synth config
    (design_dir / "synth" / "synth_config.yaml").write_text(
        SYNTH_CONFIG_TEMPLATE.format(design_name=design_name))

    # Write program.md
    (design_dir / "program.md").write_text(PROGRAM_MD)

    # Copy golden reference for comparison
    ref_file = src_dir / f"{design_name}_ref" / f"{design_name}_ref.v"
    if ref_file.exists():
        (design_dir / "golden").mkdir(exist_ok=True)
        shutil.copy2(ref_file, design_dir / "golden" / f"{design_name}_ref.v")

    # Initialize as standalone git repo so the harness can commit
    subprocess.run(["git", "init", "-q"], cwd=design_dir, check=True)
    subprocess.run(["git", "add", "."], cwd=design_dir, check=True)
    subprocess.run(
        ["git", "commit", "-q", "-m", f"Initial RTL-OPT baseline: {design_name}"],
        cwd=design_dir, check=True,
    )

    print(f"  OK {design_name} -> {design_dir}")
    return True


def main():
    parser = argparse.ArgumentParser(description="Set up RTL-OPT benchmark designs")
    parser.add_argument("--src", required=True, help="Path to RTL-OPT-20C5/benchmark/")
    parser.add_argument("--dry-run", action="store_true", help="Show what would be created")
    args = parser.parse_args()

    src_dir = Path(args.src).resolve()
    if not src_dir.exists():
        print(f"Error: {src_dir} not found")
        return 1

    designs = find_designs(src_dir)
    print(f"Found {len(designs)} RTL-OPT designs with references:")

    ok = 0
    for name in designs:
        if setup_design(name, src_dir, args.dry_run):
            ok += 1

    print(f"\nSet up {ok}/{len(designs)} designs under {DESIGNS_DIR}/rtlopt_*/")
    return 0


if __name__ == "__main__":
    exit(main())
