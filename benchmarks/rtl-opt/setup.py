#!/usr/bin/env python3
"""Set up RTL-OPT benchmark designs for AutoSilicon.

Reads designs from the RTL-OPT-20C5 download, creates per-design directories
under designs/rtlopt_<name>/ with Makefile, synth config, and program.md.

Usage:
    python3 benchmarks/rtl-opt/setup.py --src ~/Downloads/RTL-OPT-20C5/benchmark
"""

import argparse
import os
import shutil
import subprocess
from pathlib import Path

PROJ_ROOT = Path(__file__).resolve().parent.parent.parent
DESIGNS_DIR = PROJ_ROOT / "designs"
TEMPLATE_DIR = Path(__file__).resolve().parent

# Designs that have _ref counterparts (the suboptimal ones we optimize)
# Exclude _ref dirs — those are the human-optimized references
def find_designs(src_dir: Path) -> list[str]:
    """Find all suboptimal designs (those without _ref suffix)."""
    designs = []
    for d in sorted(src_dir.iterdir()):
        if d.is_dir() and not d.name.endswith("_ref"):
            ref_dir = src_dir / f"{d.name}_ref"
            if ref_dir.exists():
                designs.append(d.name)
    return designs


MAKEFILE_TEMPLATE = r"""# AutoSilicon — RTL-OPT Benchmark: {design_name}
# Auto-generated by benchmarks/rtl-opt/setup.py

.PHONY: all lint test synth-one clean

DESIGN_DIR := $(shell pwd)
PROJ_ROOT  := $(DESIGN_DIR)/../..
INFRA_DIR  := $(PROJ_ROOT)/infra

RTL_DIR    := $(DESIGN_DIR)/rtl
RTL_FILES  := $(RTL_DIR)/{design_name}.v

VENV_PYTHON := $(shell test -x $(PROJ_ROOT)/.venv/bin/python3 && echo $(PROJ_ROOT)/.venv/bin/python3)
PYTHON := $(or $(PYTHON),$(if $(VENV_PYTHON),$(VENV_PYTHON),python3))

IVERILOG := iverilog
VVP := vvp

LINT_TOP := {design_name}

all: lint

# ── Lint ──────────────────────────────────────────────────────
lint:
	@echo "Linting {design_name}..."
	verilator --lint-only -Wall \
		-Wno-UNUSEDSIGNAL -Wno-UNUSEDPARAM -Wno-WIDTHTRUNC -Wno-WIDTHEXPAND \
		-Wno-CASEINCOMPLETE -Wno-UNOPTFLAT -Wno-DECLFILENAME \
		-Wno-LATCH -Wno-COMBDLY -Wno-MULTIDRIVEN -Wno-BLKSEQ \
		-Wno-EOFNEWLINE -Wno-WIDTHCONCAT -Wno-GENUNNAMED \
		--top-module $(LINT_TOP) \
		$(RTL_FILES)
	@echo "{design_name} lint passed."

# ── Test (co-simulation against original) ────────────────────
# Compares outputs of the (possibly modified) design against the
# frozen original copy. Uses random stimulus.
tb/cosim_tb.vvp: $(RTL_FILES) tb/original.v tb/cosim_tb.v
	$(IVERILOG) -o $@ tb/cosim_tb.v $(RTL_FILES) tb/original.v

test: tb/cosim_tb.vvp
	@echo "Running co-simulation test for {design_name}..."
	cd tb && $(VVP) -N cosim_tb.vvp > test_output.log 2>&1
	@if grep -q "PASS" tb/test_output.log && ! grep -q "FAIL" tb/test_output.log; then \
		echo "{design_name}: PASS"; \
	else \
		echo "{design_name}: FAIL"; \
		cat tb/test_output.log; \
		exit 1; \
	fi
	@echo '<?xml version="1.0" encoding="utf-8"?>' > tb/results.xml
	@echo '<testsuites><testsuite name="{design_name}" tests="1">' >> tb/results.xml
	@echo '  <testcase name="test_cosim" classname="{design_name}"/>' >> tb/results.xml
	@echo '</testsuite></testsuites>' >> tb/results.xml

# ── Synthesis ─────────────────────────────────────────────────
synth-one:
	@echo "Synthesizing {design_name}..."
	$(PYTHON) $(INFRA_DIR)/synth_sweep.py --design-dir $(DESIGN_DIR) --single

# ── Clean ─────────────────────────────────────────────────────
clean:
	rm -rf obj_dir/ sim_build/ __pycache__/
	rm -rf synth/results/*
	rm -f tb/cosim_tb.vvp tb/test_output.log tb/results.xml
"""


